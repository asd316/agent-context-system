class Activate(Base):
    def setUp(self):
        super().setUp()
        self.f.cli("build")
        self.claude = self.f.clients["claude-code"]
        self.dsh = self.f.clients["dsh"]

    def test_install_rules_links_and_manual_only(self):
        r = self.f.cli("activate")
        by = {c["client"]: c for c in r["clients"]}
        self.assertEqual(r["skipped_clients"][0]["client"], "pi")
        rules_file = self.claude / "CLAUDE.md"
        self.assertFalse(rules_file.is_symlink())
        self.assertEqual(rules_file.read_text(encoding="utf-8"), self.f.built("orchestrator"))
        self.assertEqual((self.dsh / "AGENTS.md").read_text(encoding="utf-8"), self.f.built("executor"))

        lib = self.f.repo / "shared/skills"
        sk = self.claude / "skills"
        self.assertEqual(os.readlink(sk / "core-a"), str(lib / "core-a"))
        self.assertEqual(os.readlink(sk / "router-top"), str(lib / "routers/router-top"))
        # Referenced entry 的来源在 Skill Library 之外: 按 catalog.entry_path 链到 source
        self.assertEqual(os.readlink(sk / "ext-g"), str(self.f.root / "ext/ext-g"))
        self.assertEqual(sorted(by["claude-code"]["skipped"]), ["missing-e"])
        self.assertFalse((sk / "native-c").exists())
        # frontmatter 模式: 真目录,SKILL.md 带标记,来源不变,其余文件软链到来源
        self.assertFalse((sk / "manual-b").is_symlink())
        self.assertIn("disable-model-invocation: true", (sk / "manual-b/SKILL.md").read_text(encoding="utf-8"))
        self.assertNotIn("disable-model-invocation", (lib / "manual-b/SKILL.md").read_text(encoding="utf-8"))
        self.assertEqual(os.readlink(sk / "manual-b/ref.md"), str(lib / "manual-b/ref.md"))
        # skip 模式不装 Manual-only;executor 没有 Router
        self.assertEqual(sorted(os.listdir(self.dsh / "skills")), ["core-a", "ext-g"])

