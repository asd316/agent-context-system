        def add(name, category, *parents):
            a = ["add", "--name", name, "--category", category, "--actor", "human"]
            for x in parents:
                a += ["--parent", x]
            return self.f.cli(*a)["id"]
        a_skill = add("A-skills", "Skill")
        add("skill-kid", "Skill", a_skill)
        kb = add("B-kb", "Knowledge")
