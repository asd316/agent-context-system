        for c in r["clients"]:
            self.assertEqual((c["rules_changed"], c["linked"], c["unlinked"], c["conflicts"]), (False, [], [], []))
        self.assertEqual(sorted(str(p.relative_to(self.f.home)) for p in self.f.home.rglob("*")), snap)

