class Sync(Base):
    def test_pull_then_build_and_activate_only_on_change(self):
        remote = self.f.root / "remote.git"
        subprocess.run(["git", "clone", "-q", "--bare", str(self.f.repo), str(remote)], check=True)
        git(self.f.repo, "remote", "add", "origin", str(remote))
        git(self.f.repo, "fetch", "-q", "origin")
        git(self.f.repo, "branch", "-q", "--set-upstream-to=origin/main")
        other = self.f.root / "other"
        subprocess.run(["git", "clone", "-q", str(remote), str(other)], check=True)
        log = self.f.root / "sync.log"
        env = {**os.environ, "NODE_INDEX_REPO": str(self.f.repo), "NODE_INDEX_PYTHON": sys.executable,
               "NODE_INDEX_SYNC_LOG": str(log), "NODE_INDEX_DB": self.f.db}

        def sync():
            return subprocess.run(["/bin/sh", str(REPO / "bin/node-index-sync")], env=env, capture_output=True, text=True)

        self.assertEqual(sync().returncode, 0)
        self.assertFalse(log.exists())  # 没有新提交: 不 build,不写日志
        self.assertFalse((self.f.clients["claude-code"] / "CLAUDE.md").exists())

        self.f.write(other / "shared/rules/remote.md", rule("remote", "general", "FROMREMOTE", order=5))
        git(other, "add", "-A"); git(other, "-c", "user.email=o@x", "-c", "user.name=o", "commit", "-q", "-m", "r")
        git(other, "push", "-q")
        p = sync()
        self.assertEqual(p.returncode, 0, log.read_text(encoding="utf-8"))
        self.assertIn("FROMREMOTE", (self.f.clients["claude-code"] / "CLAUDE.md").read_text(encoding="utf-8"))
        self.assertIn("ok activate", log.read_text(encoding="utf-8"))

        self.f.write(other / "shared/rules/broken.md", "没有 frontmatter\n")
        git(other, "add", "-A"); git(other, "-c", "user.email=o@x", "-c", "user.name=o", "commit", "-q", "-m", "b")
        git(other, "push", "-q")
        self.assertEqual(sync().returncode, 1)
        self.assertIn("FAIL build", log.read_text(encoding="utf-8"))
        self.assertIn("FROMREMOTE", (self.f.clients["claude-code"] / "CLAUDE.md").read_text(encoding="utf-8"))


