ROUTER_BEGIN = "<!-- BEGIN MEMBER LIST (generated by node-index build) -->"
ROUTER_END = "<!-- END MEMBER LIST -->"


def rule(rid, kind, body, order=0, applies=None):
    head = f"id: {rid}\ntitle: {rid}\nkind: {kind}\norder: {order}\nadded: 2026-10-23\n"
    if applies:
        head += f"applies_to: [{applies}]\n"
    return f"---\n{head}---\n\n{body}\n"


def git(cwd, *args):
    return subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, check=True).stdout.strip()


