class Apply(Base):
    def state(self):
        return json.loads((self.f.repo / "host/apply-state.json").read_text(encoding="utf-8"))

    def add_remote(self):
        remote = self.f.root / "remote.git"
        subprocess.run(["git", "init", "-q", "--bare", str(remote)], check=True)
        git(self.f.repo, "remote", "add", "origin", str(remote))
        git(self.f.repo, "push", "-q", "-u", "origin", "main")
        return remote

    def test_apply_commits_and_pushes(self):
        remote = self.add_remote()
        self.f.write(self.f.repo / "shared/rules/new.md", rule("new", "general", "NEWRULE", order=99))
        r = self.f.cli("apply")
        self.assertEqual([s["step"] for s in r["steps"]], ["build", "activate", "commit", "push"])
        self.assertTrue(all(s["ok"] for s in r["steps"]))
        self.assertTrue(r["pushed"])
        self.assertEqual(git(remote, "rev-parse", "--short", "main"), r["commit"])
        self.assertIn("NEWRULE", (self.f.clients["claude-code"] / "CLAUDE.md").read_text(encoding="utf-8"))
        s = self.state()
        self.assertEqual((s["state"], s["commit"], s["pushed"], s["head"]), ("done", r["commit"], True, r["commit"]))
        r2 = self.f.cli("apply")
        self.assertIsNone(r2["commit"])  # 没有改动就不提交

    def test_push_failure_keeps_changes_and_marks_unpushed(self):
        self.f.write(self.f.repo / "shared/rules/new.md", rule("new", "general", "NEWRULE", order=99))
        r = self.f.cli("apply")  # 没有 remote: push 必然失败
        self.assertFalse(r["pushed"])
        self.assertIsNotNone(r["commit"])
        self.assertTrue(r["steps"][-1]["detail"].startswith("未推送"))
        self.assertIn("NEWRULE", (self.f.clients["claude-code"] / "CLAUDE.md").read_text(encoding="utf-8"))
        s = self.state()
        self.assertEqual((s["state"], s["pushed"]), ("done", False))
        self.assertTrue(s["unpushed_reason"])

    def test_stops_at_first_failure(self):
        head = git(self.f.repo, "rev-parse", "HEAD")
