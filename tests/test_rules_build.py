class Build(Base):
    def test_profiles_filter_order_and_render(self):
        r = self.f.cli("build")
        self.assertEqual([x["profile"] for x in r["profiles"]], ["orchestrator", "executor"])
        orch, exe = self.f.built("orchestrator"), self.f.built("executor")
        # kind 固定顺序;同 kind 内按 order,而不是按 id
        marks = ["GEN", "ORCHONLY", "## Index", "## Required read", "DISPATCH", "MAINT"]
        self.assertEqual([orch.index(m) for m in marks], sorted(orch.index(m) for m in marks))
        self.assertNotIn("ORCHONLY", exe)
        self.assertNotIn("DISPATCH", exe)
        self.assertIn("MAINT", exe)
        self.assertIn("深度 2", orch)
        self.assertNotIn("{{", orch)
        sop = self.f.repo / "shared/reference/sops/config-method.md"
        self.assertIn(f"- 配置软件: `{sop}`", orch)
        self.assertIn("- 浏览器: `~/fallback.md`", orch)
        self.assertTrue(orch.startswith("<!-- node-index build: profile=orchestrator built="))
        self.assertIn("source=" + git(self.f.repo, "rev-parse", "--short", "HEAD"), orch.split("\n")[0])

    def test_skills_txt(self):
        self.f.cli("build")
        self.assertEqual(self.f.built("orchestrator", "skills.txt").splitlines()[1:],
                         ["core-a", "ext-g", "manual-b manual-only", "missing-e", "native-c", "router-top"])
        self.assertEqual(self.f.built("executor", "skills.txt").splitlines()[1:],
                         ["core-a", "ext-g", "manual-b manual-only", "missing-e", "native-c"])

