BEGIN = "<!-- BEGIN MEMBER LIST (generated by node-index build) -->"
END = "<!-- END MEMBER LIST -->"
GUIDE = "## Selection guide\n\n做动效选 `old-skill`;不确定时先问用户。"
REVISED = "## Selection guide\n\n做动效选 `animate`;报税不在这里。不确定时先问用户。"


class Gateway:
    """按提示词里的检查单位决定回复。mode 可改成 bad_office (office 永远回坏 JSON)。"""

    def __init__(self):
        self.prompts = []
        self.mode = "ok"
        outer = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def do_POST(self):
                body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
                prompt = body["messages"][1]["content"]
                outer.prompts.append(body)
                feedback = len(body["messages"]) > 2
                if "分类: `design` " in prompt:
                    # 第一次给一个不存在的分类,应被退回重问
                    target = "office" if feedback else "nope"
                    out = {"findings": [{"skill": "tax-helper", "problem": "它讲报税,与设计无关",
                                         "suggestion": "移到办公文档", "move_to": target, "copy_to": None}]}
                elif "分类: `office` " in prompt and outer.mode == "bad_office":
                    out = None
                elif "Router: `router-design`" in prompt:
                    out = {"consistent": False, "issues": ["guide 提到的 old-skill 不在 Member list 里"],
                           "suggestion": "改成 animate", "revised_guide": REVISED}
                else:
                    out = {"findings": []}
                data = json.dumps({"choices": [{"message": {"content": "随便说说" if out is None else
                                                            json.dumps(out, ensure_ascii=False)}}]})
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(data.encode())

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), H)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}/v1"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def close(self):
        self.server.shutdown()
        self.server.server_close()


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


class Digest(Base):
    def setUp(self):
        super().setUp()
        self.gw = Gateway()
        self.addCleanup(self.gw.close)
        self.repo = self.root / "repo"
        sh = self.repo / "shared"
        entry = "{{entry: vendored, source: {s}, added: 2026-10-23, tier: {t}, status: active}}\n"
        write(sh / "catalog.yaml", "".join(f"{n}: " + entry.format(s=s, t=t) for n, s, t in (
            ("animate", "animate", "leaf"), ("tax-helper", "tax-helper", "leaf"), ("doc-writer", "doc-writer", "leaf"),
            ("router-design", "routers/router-design", "router"))))
        write(sh / "categories.yaml", "design: {name: 设计, router: router-design, members: [animate, tax-helper]}\n"
                                      "office: {name: 办公文档, router: null, members: [doc-writer]}\n")
        for n, d in (("animate", "构建网页动画"), ("tax-helper", "个人所得税申报"), ("doc-writer", "写 Word 文档")):
            write(sh / "skills" / n / "SKILL.md", f"---\nname: {n}\ndescription: {d}\n---\n\n正文 {n}\n")
        self.router = sh / "skills/routers/router-design/SKILL.md"
        write(self.router, f"---\nname: router-design\ndescription: 设计入口\n---\n\n{GUIDE}\n\n{BEGIN}\n{END}\n")
        write(self.repo / "host/host.yml", "host: test-host\nclients: {}\nknowledge_root: /tmp\n")
        self.env_file = self.root / "t.env"
        self.env_file.write_text(f"OPENAI_BASE_URL={self.gw.url}\nOPENAI_API_KEY={FAKE_KEY}\nOPENAI_MODEL=m\n"
                                 "SUMMARY_RETRY_SLEEP=0\nSUMMARY_TIMEOUT_SECONDS=5\n", encoding="utf-8")

    def digest(self, *args, expect=0, cwd=None):
        p = subprocess.run([sys.executable, str(BIN), "digest", "--env", str(self.env_file), *args, "--json",
                            "--db", self.db], cwd=cwd or self.repo, capture_output=True, text=True,
                           env={**os.environ, "NODE_INDEX_REPO": str(self.repo), "NODE_INDEX_DB": ""})
        self.assertEqual(p.returncode, expect, p.stderr)
        self.assertNotIn(FAKE_KEY, p.stdout + p.stderr)
        return json.loads(p.stdout or p.stderr)

    def reports(self):
        import yaml
        return [yaml.safe_load(f.read_text(encoding="utf-8")) for f in sorted((self.repo / "shared/inbox").glob("R-*.yaml"))]

    def test_findings_become_digest_reports_with_concrete_suggestions(self):
        r = self.digest()
        check(r, response_schema("digest"))
        self.assertEqual(r["targets"], 3)  # design、office 两个归类单位 + 一个 Router
        self.assertEqual(sorted(x["key"] for x in r["reports"]),
                         ["category-fit:design:tax-helper", "router-guide:router-design"])
        self.assertEqual((r["failed"], r["duplicates"]), ([], []))
        by = {x["evidence"].split("\n")[0]: x for x in self.reports()}
        fit = by["Digest 条目: category-fit:design:tax-helper"]
        self.assertEqual((fit["kind"], fit["status"], fit["from"]["client"], fit["from"]["host"]),
                         ("digest", "pending", "node-index-digest", "test-host"))
        self.assertIn("node-index category move tax-helper --from design --to office", fit["reason"])
        self.assertIn("个人所得税申报", fit["evidence"])  # 取材自 SKILL.md
        guide = by["Digest 条目: router-guide:router-design"]
        self.assertIn("old-skill", guide["reason"])
        change = guide["change"]
        self.assertEqual(change["target"], "shared/skills/routers/router-design/SKILL.md")
        self.assertEqual(change["replace"]["new"], REVISED)
        self.assertEqual(self.router.read_text(encoding="utf-8").count(change["replace"]["old"]), 1)  # 可直接批准应用
        # Router 单位看到的是按 categories.yaml 现算的 Member list,不是 SKILL.md 里可能过时的区段
        router_prompt = next(b for b in self.gw.prompts if "Router: `router-design`" in b["messages"][1]["content"])
        self.assertIn("`tax-helper`", router_prompt["messages"][1]["content"])
        self.assertEqual(router_prompt["thinking"], {"type": "disabled"})
        state = json.loads((self.repo / "host/digest-state.json").read_text(encoding="utf-8"))
        self.assertEqual(sorted(state["reports"]), sorted(x["id"] for x in r["reports"]))

    def test_open_report_for_same_target_is_not_duplicated_closed_one_is(self):
        first = self.digest()
        again = self.digest()
        self.assertEqual(again["reports"], [])
        self.assertEqual(sorted(again["duplicates"]), sorted(x["key"] for x in first["reports"]))
        self.assertEqual(len(self.reports()), 2)
        fit = next(x for x in first["reports"] if x["key"].startswith("category-fit"))
        env = {**os.environ, "NODE_INDEX_REPO": str(self.repo)}
        subprocess.run([sys.executable, str(BIN), "inbox", "resolve", fit["id"], "--status", "rejected",
                        "--decided-by", "user", "--instruction", "先不动", "--by", "t"], env=env, check=True,
                       capture_output=True)
        third = self.digest()
        self.assertEqual([x["key"] for x in third["reports"]], [fit["key"]])

    def test_if_due_skips_within_seven_days(self):
        self.digest()
        calls = len(self.gw.prompts)
        r = self.digest("--if-due")
        self.assertTrue(r["skipped"])
        check(r, response_schema("digest"))
        self.assertEqual(len(self.gw.prompts), calls)
        (self.repo / "host/digest-state.json").write_text(json.dumps({"last_run": "2026-01-01T00:00:00"}))
        self.assertNotIn("skipped", self.digest("--if-due"))

    def test_failed_unit_is_reported_and_run_not_recorded(self):
        self.gw.mode = "bad_office"
        r = self.digest()
        self.assertEqual([x["key"] for x in r["failed"]], ["category-fit:office"])
        self.assertIn("多次重试仍不合格", r["failed"][0]["reason"])
        self.assertEqual(len(r["reports"]), 2)  # 其余单位照常出 Report
        self.assertFalse((self.repo / "host/digest-state.json").exists())  # 下次仍到期,会重跑

    def test_dry_run_needs_no_env_and_any_dir(self):
        self.env_file.unlink()
        r = self.digest("--dry-run", cwd=self.root)
        check(r, response_schema("digest"))
        self.assertEqual(r["target_keys"], ["category-fit:design", "category-fit:office", "router-guide:design"])
        self.assertIn("tax-helper", r["sample_prompt"])
        self.assertEqual(self.gw.prompts, [])
        self.assertFalse((self.repo / "shared/inbox").exists())

    def test_refused_outside_repo_and_without_host_config(self):
        self.digest(cwd=self.root, expect=5)
        (self.repo / "host/host.yml").unlink()
        self.assertEqual(self.digest(expect=2)["error"], "bad_input")
        self.assertEqual(self.gw.prompts, [])  # 没有 Host config 时不调用模型


if __name__ == "__main__":
    unittest.main()
