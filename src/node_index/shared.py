@dataclass(frozen=True)
class RuleBlock:
    id: str
    title: str
    kind: RuleKind
    applies_to: frozenset  # of Profile;空集表示全部
    order: int
    added: date
    reason: str | None
    source: str | None
    body: str
    tree_exclude_categories: tuple = ()  # 只用于 index 块: {{tree}} 略去这些 Category 的最上层节点
    tree_collapse_categories: tuple = ()  # 只用于 index 块: 这些 Category 的最上层节点只列一行,不展开
    tree_categories_only: tuple = ()  # 只用于 index 块: 这些 Category 的最上层节点下只列共享 Category,不列磁盘目录

    def applies(self, profile):
        return not self.applies_to or profile in self.applies_to


def load_rule(path):
    path = Path(path)
    meta, body = split_frontmatter(path.read_text(encoding="utf-8"), path)
    f = _Fields(meta, path)
    rid = f.match("id", SLUG)
    if rid != path.stem:
        raise ShapeError(path, f"id {rid!r} 与文件名不一致")
    try:
        applies = frozenset(Profile(x) for x in f.list("applies_to"))
    except ValueError as e:
        raise ShapeError(path, f"applies_to 不合法: {e}") from None
    r = RuleBlock(id=rid, title=f.str("title"), kind=f.enum("kind", RuleKind), applies_to=applies,
                  order=f.int("order", 0), added=f.date("added"), reason=f.str("reason", False),
                  source=f.match("source", REPORT_ID, False), body=body,
                  tree_exclude_categories=tuple(f.list("tree_exclude_categories")),
                  tree_collapse_categories=tuple(f.list("tree_collapse_categories")),
                  tree_categories_only=tuple(f.list("tree_categories_only")))
    f.done()
    for field in ("tree_exclude_categories", "tree_collapse_categories", "tree_categories_only"):
        bad = [c for c in getattr(r, field) if c not in CATEGORIES]
        if bad:
            raise ShapeError(path, f"{field} 不合法: {bad},可选 {list(CATEGORIES)}")
        if getattr(r, field) and r.kind is not RuleKind.INDEX:
            raise ShapeError(path, f"{field} 只能用于 kind: index")
    if not body.strip():
        raise ShapeError(path, "正文为空")
    return r


def load_rules(p):
    """按 Build 的拼接顺序返回: kind 定义顺序,再 order,再 id。"""
    kinds = list(RuleKind)
    rules = [load_rule(x) for x in sorted(p.rules.glob("*.md"))]
    return sorted(rules, key=lambda r: (kinds.index(r.kind), r.order, r.id))


@dataclass(frozen=True)
class RequiredRead:
    task: str
    sop: str
    fallback: str | None  # SOP 尚未导入本仓库时暂读的路径 (本机特定)


def parse_required_read(rule):
    """required-read 块的正文是 YAML 映射: task (任务类型)、sop (SOP id)、fallback (可空)。"""
    source = f"shared/rules/{rule.id}.md"
    try:
        data = yaml.safe_load(rule.body)
    except yaml.YAMLError as e:
        raise ShapeError(source, f"required-read 正文应为 YAML 映射: {e}") from None
    f = _Fields(data, f"{source} 正文")
    r = RequiredRead(task=f.str("task"), sop=f.match("sop", SLUG), fallback=f.str("fallback", False))
    f.done()
    return r


