@dataclass(frozen=True)
class MemberRef:
    kind: MemberKind
    id: str

    @classmethod
    def parse(cls, text, source="member"):
        for kind in (MemberKind.SOP, MemberKind.LESSON):
            prefix = kind.value + ":"
            if text.startswith(prefix):
                rid = text[len(prefix):]
                pattern = SLUG if kind is MemberKind.SOP else LESSON_ID
                if not pattern.match(rid):
                    raise ShapeError(source, f"成员引用格式不对: {text!r}")
                return cls(kind, rid)
        if ":" in text or not text:
            raise ShapeError(source, f"成员引用格式不对: {text!r}")
        return cls(MemberKind.SKILL, text)

    def __str__(self):
        return self.id if self.kind is MemberKind.SKILL else f"{self.kind.value}:{self.id}"


@dataclass(frozen=True)
class Category:
    id: str
    name: str
    router: str | None
    members: tuple = ()  # of MemberRef,保持文件中的顺序

    @property
    def parent(self):
        return self.id.rsplit("/", 1)[0] if "/" in self.id else None

    def to_dict(self):
        return {"name": self.name, "router": self.router, "members": [str(m) for m in self.members]}


def parse_categories(data, source):
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ShapeError(source, "categories 应为映射")
    out = {}
    for cid, raw in data.items():
        if not isinstance(cid, str) or not CATEGORY_ID.match(cid):
            raise ShapeError(source, f"Category id 格式不对: {cid!r}")
        f = _Fields(raw, f"{source} [{cid}]")
        members = tuple(MemberRef.parse(m, f.source) for m in f.list("members"))
        if len(set(members)) != len(members):
            raise ShapeError(f.source, "members 有重复")
        out[cid] = Category(id=cid, name=f.str("name"), router=f.str("router", False), members=members)
        f.done()
    for c in out.values():
        if c.parent and c.parent not in out:
            raise ShapeError(source, f"{c.id} 的父 Category {c.parent} 不存在")
    return out


def load_categories(p):
    return parse_categories(_read_yaml(p.categories), p.categories)


def categories_to_dict(categories):
    return {cid: categories[cid].to_dict() for cid in sorted(categories)}


