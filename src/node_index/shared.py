@dataclass(frozen=True)
class DiffChange:
    target: str
    diff: str


@dataclass(frozen=True)
class ReplaceChange:
    target: str
    old: str
    new: str


@dataclass(frozen=True)
class ReportFrom:
    client: str
    position: Position
    host: str


@dataclass(frozen=True)
class Resolution:
    decided_by: str
    instruction: str | None
    outcome: Outcome | None  # rejected 时为 None
    changes: tuple
    at: datetime


@dataclass(frozen=True)
class Report:
    id: str
    kind: ReportKind
    title: str
    reason: str
    evidence: str
    from_: ReportFrom
    at: datetime
    change: DiffChange | ReplaceChange | None = None
    status: ReportStatus = ReportStatus.PENDING
    claimed_by: str | None = None
    resolution: Resolution | None = None

    def to_dict(self):
        c = self.change
        change = (None if c is None else {"target": c.target, "diff": c.diff} if isinstance(c, DiffChange)
                  else {"target": c.target, "replace": {"old": c.old, "new": c.new}})
        r = self.resolution
        resolution = None if r is None else {
            "decided_by": r.decided_by, "instruction": r.instruction,
            "outcome": r.outcome.value if r.outcome else None, "changes": list(r.changes), "at": _iso(r.at)}
        return {"id": self.id, "kind": self.kind.value, "title": self.title, "reason": self.reason,
                "evidence": self.evidence,
                "from": {"client": self.from_.client, "position": self.from_.position.value, "host": self.from_.host},
                "at": _iso(self.at), "change": change, "status": self.status.value,
                "claimed_by": self.claimed_by, "resolution": resolution}


def _parse_change(f):
    if f is None:
        return None
    target = f.str("target")
    if Path(target).is_absolute() or ".." in Path(target).parts:
        raise ShapeError(f.source, f"target 应为仓库内相对路径: {target!r}")
    diff = f.str("diff", False)
    rep = f.mapping("replace", False)
    f.done()
    if (diff is None) == (rep is None):
        raise ShapeError(f.source, "diff 与 replace 须恰好有一个")
    if diff is not None:
        return DiffChange(target, diff)
    old, new = rep._get("old", False), rep._get("new", False)
    if not isinstance(old, str) or not old or not isinstance(new, str):
        raise ShapeError(rep.source, "replace 须有非空字符串 old 与字符串 new")
    rep.done()
    return ReplaceChange(target, old, new)


def parse_report(data, source):
    f = _Fields(data, source)
    rid = f.match("id", REPORT_ID)
    kind = f.enum("kind", ReportKind)
    fr = f.mapping("from")
    frm = ReportFrom(client=fr.str("client"), position=fr.enum("position", Position), host=fr.str("host"))
    fr.done()
    change = _parse_change(f.mapping("change", False))
    status = f.enum("status", ReportStatus)
    claimed_by = f.str("claimed_by", False)
    rf = f.mapping("resolution", False)
    resolution = None
    if rf is not None:
        resolution = Resolution(decided_by=rf.str("decided_by"), instruction=rf.str("instruction", False),
                                outcome=rf.enum("outcome", Outcome, required=False),
                                changes=tuple(rf.list("changes")), at=rf.datetime("at"))
        rf.done()
    report = Report(id=rid, kind=kind, title=f.str("title"), reason=f.str("reason"), evidence=f.str("evidence"),
                    from_=frm, at=f.datetime("at"), change=change, status=status, claimed_by=claimed_by,
                    resolution=resolution)
    f.done()
    validate_report(report, source)
    return report


def validate_report(r, source):
    """状态之间的约束。新建或修改 Report 后写盘前也调用它。"""
    if r.kind is ReportKind.RULE_CHANGE and r.change is None:
        raise ShapeError(source, "rule-change 必须带 change (Proposal)")
    if (r.status is ReportStatus.IN_PROGRESS) != (r.claimed_by is not None):
        raise ShapeError(source, "claimed_by 当且仅当 status 为 in-progress 时填写")
    closed = r.status in (ReportStatus.RESOLVED, ReportStatus.REJECTED)
    if closed != (r.resolution is not None):
        raise ShapeError(source, "resolution 当且仅当 status 为 resolved/rejected 时填写")
    if r.status is ReportStatus.RESOLVED and r.resolution.outcome in (None, Outcome.SUPERSEDED):
        raise ShapeError(source, "resolved 的 resolution 须有 outcome (as-proposed 或 modified)")
    if r.status is ReportStatus.REJECTED and r.resolution.outcome not in (None, Outcome.SUPERSEDED):
        raise ShapeError(source, "rejected 的 resolution 只能不填 outcome 或填 superseded")


def load_report(path):
    path = Path(path)
    r = parse_report(_read_yaml(path), path)
    if r.id != path.stem:
        raise ShapeError(path, f"id {r.id!r} 与文件名不一致")
    return r


def load_reports(p):
    return {x.id: x for x in map(load_report, sorted(p.inbox.glob("R-*.yaml")))}


# ---- Decision log ----

@dataclass(frozen=True)
class Decision:
    at: datetime
    target: str
    action: str
    result: DecisionResult
    by: str
    instruction: str | None = None
    note: str | None = None
    session: str | None = None  # 执行者的会话 id,拿得到才记

    def to_dict(self):
        d = {"at": _iso(self.at), "target": self.target, "action": self.action, "result": self.result.value}
        if self.instruction is not None:
            d["instruction"] = self.instruction
        if self.note is not None:
            d["note"] = self.note
        d["by"] = self.by
        if self.session is not None:
            d["session"] = self.session
        return d


def parse_decision(data, source):
    f = _Fields(data, source)
    d = Decision(at=f.datetime("at"), target=f.str("target"), action=f.str("action"),
                 result=f.enum("result", DecisionResult), by=f.str("by"),
                 instruction=f.str("instruction", False), note=f.str("note", False),
                 session=f.str("session", False))
    f.done()
    if d.instruction is None and d.note is None:
        raise ShapeError(source, "instruction 与 note 至少填一个")
    return d


def append_decision(p, decision):
    """只追加一行。整行一次 write,O_APPEND 下多进程追加不会交错。"""
    parse_decision(decision.to_dict(), "decision")
    line = json.dumps(decision.to_dict(), ensure_ascii=False) + "\n"
    p.decisions.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(p.decisions, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o644)
    try:
        os.write(fd, line.encode("utf-8"))
    finally:
        os.close(fd)


def load_decisions(p):
    if not p.decisions.exists():
        return []
    out = []
    for n, line in enumerate(p.decisions.read_text(encoding="utf-8").splitlines(), 1):
        if line.strip():
            try:
                data = json.loads(line)
            except json.JSONDecodeError as e:
                raise ShapeError(f"{p.decisions}:{n}", f"不是 JSON: {e}") from None
            out.append(parse_decision(data, f"{p.decisions}:{n}"))
    return out


# ---- Host config ----

@dataclass(frozen=True)
class ClientConfig:
    name: str
    rules_path: Path
    skills_dir: Path
    profile: Profile
    manual_only_mode: ManualOnlyMode


@dataclass(frozen=True)
class HostConfig:
    host: str
    clients: dict  # name → ClientConfig
    knowledge_root: Path
    scan_roots: list = field(default_factory=list)  # 每项格式同 config/scope.yml 的 roots


def _expand(v):
    return Path(v).expanduser()


def parse_host(data, source):
    f = _Fields(data, source)
    host = f.match("host", SLUG)
    cf = f.mapping("clients")
    clients = {}
    for name in cf.data:
        c = cf.mapping(name)
        clients[name] = ClientConfig(name=name, rules_path=_expand(c.str("rules_path")),
                                     skills_dir=_expand(c.str("skills_dir")), profile=c.enum("profile", Profile),
                                     manual_only_mode=c.enum("manual_only_mode", ManualOnlyMode))
        c.done()
    roots = f._get("scan_roots", False) or []
    if not isinstance(roots, list) or not all(isinstance(r, dict) and r.get("path") for r in roots):
        raise ShapeError(source, "scan_roots 应为列表,每项至少有 path")
    cfg = HostConfig(host=host, clients=clients, knowledge_root=_expand(f.str("knowledge_root")), scan_roots=roots)
    f.done()
    return cfg


def load_host(p, path=None):
    path = Path(path) if path else p.host
    if not path.exists():
        raise ShapeError(path, "Host config 不存在;请新建 host/host.yml 并按本机填写")
    return parse_host(_read_yaml(path), path)


# ---- 跨文件一致性 ----

def cross_check(catalog, categories, sop_ids, lesson_ids):
    """返回问题清单 (空即一致)。不抛错: 这些问题要报告给维护者,而不是让读命令失败。"""
    problems = []
    for c in sorted(categories.values(), key=lambda c: c.id):
        if c.router is not None:
            e = catalog.get(c.router)
            if e is None or e.tier is not Tier.ROUTER:
                problems.append(f"{c.id}: router {c.router} 不是 tier=router 的 Catalog entry")
        for m in c.members:
            if m.kind is MemberKind.SKILL and m.id not in catalog:
                problems.append(f"{c.id}: 成员 {m} 不在 Catalog 中")
            elif m.kind is MemberKind.SOP and m.id not in sop_ids:
                problems.append(f"{c.id}: 成员 {m} 对应的 SOP 不存在")
            elif m.kind is MemberKind.LESSON and m.id not in lesson_ids:
                problems.append(f"{c.id}: 成员 {m} 对应的 Lesson 不存在")
    return problems
