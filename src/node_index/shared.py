# ---- 解析工具 ----

class _Fields:
    """从一个映射里按字段取值;未知字段报错,防止拼错的键被静默忽略。"""

    def __init__(self, data, source):
        if not isinstance(data, dict):
            raise ShapeError(source, f"应为映射,实际是 {type(data).__name__}")
        self.data, self.source, self.used = data, source, set()

    def _get(self, name, required):
        self.used.add(name)
        v = self.data.get(name)
        if required and (v is None or v == ""):
            raise ShapeError(self.source, f"缺少必填字段 {name}")
        return v

    def str(self, name, required=True):
        v = self._get(name, required)
        if v is None or v == "":
            return None
        if not isinstance(v, str):
            raise ShapeError(self.source, f"{name} 应为字符串")
        return v

    def match(self, name, pattern, required=True):
        v = self.str(name, required)
        if v is not None and not pattern.match(v):
            raise ShapeError(self.source, f"{name} 格式不对: {v!r}")
        return v

    def enum(self, name, cls, required=True):
        v = self._get(name, required)
        if v is None:
            return None
        try:
            return cls(v)
        except ValueError:
            raise ShapeError(self.source, f"{name} 不合法: {v!r},可选 {[m.value for m in cls]}") from None

    def bool(self, name, default):
        v = self._get(name, False)
        if v is None:
            return default
        if not isinstance(v, bool):
            raise ShapeError(self.source, f"{name} 应为 true/false")
        return v

    def int(self, name, default):
        v = self._get(name, False)
        if v is None:
            return default
        if isinstance(v, bool) or not isinstance(v, int):
            raise ShapeError(self.source, f"{name} 应为整数")
        return v

    def date(self, name):
        v = self._get(name, True)
        if isinstance(v, datetime):
            raise ShapeError(self.source, f"{name} 应为日期,不带时间")
        if isinstance(v, date):
            return v
        try:
            return date.fromisoformat(str(v))
        except ValueError:
            raise ShapeError(self.source, f"{name} 不是日期: {v!r}") from None

    def datetime(self, name):
        v = self._get(name, True)
        if isinstance(v, datetime):
            return v
        try:
            return datetime.fromisoformat(str(v))
        except ValueError:
            raise ShapeError(self.source, f"{name} 不是时间: {v!r}") from None

    def list(self, name):
        v = self._get(name, False)
        if v is None:
            return []
        if not isinstance(v, list) or not all(isinstance(x, str) and x for x in v):
            raise ShapeError(self.source, f"{name} 应为非空字符串列表")
        return v

    def mapping(self, name, required=True):
        v = self._get(name, required)
        return None if v is None else _Fields(v, f"{self.source} {name}")

    def done(self):
        extra = set(self.data) - self.used
        if extra:
            raise ShapeError(self.source, f"未知字段 {sorted(extra)}")


def _read_yaml(path):
    try:
        return yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        raise ShapeError(path, f"YAML 解析失败: {e}") from None


def split_frontmatter(text, source):
    """返回 (frontmatter 映射, 正文)。文件必须以 --- 行开头,以第二个 --- 行结束 frontmatter。"""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ShapeError(source, "缺少 frontmatter (首行应为 ---)")
    for i, line in enumerate(lines[1:], 1):
        if line.strip() == "---":
            try:
                meta = yaml.safe_load("\n".join(lines[1:i])) or {}
            except yaml.YAMLError as e:
                raise ShapeError(source, f"frontmatter 解析失败: {e}") from None
            return meta, "\n".join(lines[i + 1:]).lstrip("\n")
    raise ShapeError(source, "frontmatter 没有结束的 --- 行")


def _iso(v):
    return v.isoformat(timespec="seconds") if isinstance(v, datetime) else v.isoformat()


def write_yaml(path, data):
    """确定性的 YAML 输出: 保留键顺序、中文不转义。调用方负责先排好序。"""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")


