LESSON_SECTIONS = ("情境", "问题", "正确做法")


@dataclass(frozen=True)
class Lesson:
    id: str
    topic: str
    status: LessonStatus
    merged_into: str | None
    host: str | None
    client: str
    date: date
    body: str

    @property
    def filename(self):
        return f"{self.id}-{self.topic}.md"


def _check_sections(body, source):
    pos = -1
    for name in LESSON_SECTIONS:
        m = re.search(rf"^## {name}\s*$", body, re.M)
        if not m or m.start() < pos:
            raise ShapeError(source, f"正文须依次含二级标题 {' / '.join(LESSON_SECTIONS)}")
        pos = m.start()


def load_lesson(path):
    path = Path(path)
    meta, body = split_frontmatter(path.read_text(encoding="utf-8"), path)
    f = _Fields(meta, path)
    lid = f.match("id", LESSON_ID)
    if not path.stem.startswith(lid + "-") or len(path.stem) == len(lid) + 1:
        raise ShapeError(path, f"文件名应为 {lid}-<主题>.md")
    status = f.enum("status", LessonStatus)
    merged_into = f.match("merged_into", SLUG, False)
    if (status is LessonStatus.MERGED) != (merged_into is not None):
        raise ShapeError(path, "merged_into 当且仅当 status 为 merged 时填写")
    lesson = Lesson(id=lid, topic=path.stem[len(lid) + 1:], status=status, merged_into=merged_into,
                    host=f.str("host", False), client=f.str("client"), date=f.date("date"), body=body)
    f.done()
    _check_sections(body, path)
    return lesson


def load_lessons(p):
    return {x.id: x for x in map(load_lesson, sorted(p.lessons.glob("L-*.md")))}


def render_lesson(lesson_id, topic, client, situation, problem, fix, host=None, today=None):
    """新 Lesson 的文件名与全文 (status 为 active)。返回 (filename, text)。"""
    if not LESSON_ID.match(lesson_id) or not topic or "/" in topic:
        raise ShapeError("lesson", f"id 或主题不合法: {lesson_id!r} {topic!r}")
    meta = {"id": lesson_id, "status": LessonStatus.ACTIVE.value, "merged_into": None, "host": host,
            "client": client, "date": today or date.today()}
    head = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False)
    body = "".join(f"## {name}\n\n{text.strip()}\n\n" for name, text in zip(LESSON_SECTIONS, (situation, problem, fix)))
    return f"{lesson_id}-{topic}.md", f"---\n{head}---\n\n{body}".rstrip("\n") + "\n"


@dataclass(frozen=True)
class Sop:
    id: str
    title: str
    updated: date
    from_lessons: tuple
    body: str


def load_sop(path):
    path = Path(path)
    meta, body = split_frontmatter(path.read_text(encoding="utf-8"), path)
    f = _Fields(meta, path)
    sid = f.match("id", SLUG)
    if sid != path.stem:
        raise ShapeError(path, f"id {sid!r} 与文件名不一致")
    from_lessons = tuple(f.list("from_lessons"))
    bad = [x for x in from_lessons if not LESSON_ID.match(x)]
    if bad:
        raise ShapeError(path, f"from_lessons 含非 Lesson id: {bad}")
    sop = Sop(id=sid, title=f.str("title"), updated=f.date("updated"), from_lessons=from_lessons, body=body)
    f.done()
    return sop


def load_sops(p):
    return {x.id: x for x in map(load_sop, sorted(p.sops.glob("*.md")))}


