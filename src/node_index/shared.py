def new_id(prefix, taken=(), today=None):
    """prefix 为 "R" 或 "L"。taken 是已有 ID,撞上就重抽。"""
    if prefix not in ("R", "L"):
        raise ValueError(prefix)
    day = (today or date.today()).strftime("%Y%m%d")
    taken = set(taken)
    while True:
        i = f"{prefix}-{day}-{secrets.token_hex(2)}"
        if i not in taken:
            return i


